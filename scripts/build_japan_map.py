"""Build js/japan-map-data.js for the 宿泊料金トレンド observed-markets map.

Source: Natural Earth 1:10m Admin 1 (public domain), filtered to Japan.
  curl -o admin1.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_1_states_provinces.geojson
  python3 scripts/build_japan_map.py admin1.geojson js/japan-map-data.js
Requires shapely (only for this one-off build; the site itself needs nothing).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from shapely.geometry import box, shape
from shapely.ops import linemerge, unary_union

# Same projection idea as before: equirectangular, longitude shrunk by cos(~37°).
LON_MIN, LAT_MAX, LON_SCALE, UNIT = 128.4, 45.75, 0.80, 36
MAIN_BOX = box(128.4, 30.0, 146.0, 45.75)
# Okinawa and the Amami islands are drawn in an inset in the empty top-left sea.
INSET_BOX = box(122.8, 24.0, 130.2, 28.6)
INSET = {"x": 14, "y": 14, "unit": 24, "lon_min": 122.8, "lat_max": 28.6}
TOLERANCE = 0.012
MIN_AREA = 0.003  # square degrees (~30 km²); drops reefs and islets only
INSET_MIN_AREA = 0.0008


def project(lon: float, lat: float) -> tuple[float, float]:
    return (lon - LON_MIN) * LON_SCALE * UNIT, (LAT_MAX - lat) * UNIT


def project_inset(lon: float, lat: float) -> tuple[float, float]:
    return (INSET["x"] + (lon - INSET["lon_min"]) * LON_SCALE * INSET["unit"],
            INSET["y"] + (INSET["lat_max"] - lat) * INSET["unit"])


def polygons(geometry):
    if geometry.is_empty:
        return []
    if geometry.geom_type == "Polygon":
        return [geometry]
    return [part for part in getattr(geometry, "geoms", []) if part.geom_type == "Polygon"]


def lines(geometry):
    if geometry.is_empty:
        return []
    if geometry.geom_type == "LineString":
        return [geometry]
    return [line for part in getattr(geometry, "geoms", []) for line in lines(part)]


def ring_path(coords, projector, closed=True) -> str:
    points = []
    for lon, lat in coords:
        x, y = projector(lon, lat)
        point = f"{x:.1f} {y:.1f}"
        if not points or points[-1] != point:
            points.append(point)
    if len(points) < (3 if closed else 2):
        return ""
    return "M" + "L".join(points) + ("Z" if closed else "")


def land_path(geometry, projector, min_area=MIN_AREA) -> str:
    parts = []
    for polygon in polygons(geometry):
        if polygon.area < min_area:
            continue
        polygon = polygon.simplify(TOLERANCE, preserve_topology=True)
        parts.append(ring_path(polygon.exterior.coords, projector))
    return "".join(part for part in parts if part)


def main(source: Path, output: Path) -> None:
    features = json.loads(source.read_text(encoding="utf-8"))["features"]
    prefectures = [shape(f["geometry"]).buffer(0) for f in features if f["properties"].get("adm0_a3") == "JPN"]
    land = unary_union(prefectures)
    coast = land.boundary.buffer(0.004)
    borders = linemerge(lines(unary_union([p.boundary for p in prefectures]).difference(coast).intersection(MAIN_BOX)))
    border_parts = []
    for line in lines(borders):
        if line.length < 0.02:
            continue
        border_parts.append(ring_path(line.simplify(TOLERANCE).coords, project, closed=False))
    width, height = project(146.0, 30.0)
    inset_w, inset_h = (7.4 * LON_SCALE * INSET["unit"]), (4.6 * INSET["unit"])
    payload = {
        "source": "Natural Earth 1:10m Admin 1 (public domain)",
        "width": round(width, 1), "height": round(height, 1),
        "projection": {"lonMin": LON_MIN, "latMax": LAT_MAX, "lonScale": LON_SCALE, "unit": UNIT},
        "land": land_path(land.intersection(MAIN_BOX), project),
        "borders": "".join(part for part in border_parts if part),
        "inset": {
            "label": "沖縄・奄美",
            "box": [INSET["x"] - 4, INSET["y"] - 4, round(inset_w + 8, 1), round(inset_h + 8, 1)],
            "land": land_path(land.intersection(INSET_BOX), project_inset, INSET_MIN_AREA),
        },
    }
    output.write_text(
        "// Generated by scripts/build_japan_map.py from Natural Earth (public domain). Do not edit by hand.\n"
        f"window.HotelPriceJapanMap = {json.dumps(payload, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"{output} {output.stat().st_size} bytes, viewBox 0 0 {payload['width']} {payload['height']}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
